# Ввести 2 числа. Если их произведение отрицательно, умножить его на 8, в противном
# случае увеличить его в 1.5 раза.

while True:
    try:
        a = int(input("Введите перовое целое число: "))
        b = int(input("Введите второе целое число: "))
        if a*b < 0:
            print(a*b*8)
        else:
            print(a*b*1.5)
    except ValueError:
        print("Неправильно, введите целые числа.")
        continue
    break