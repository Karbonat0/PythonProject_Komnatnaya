#Дан список размера N. Осуществить циклический сдвиг элементов списка вправо на
#одну позицию (при этом A1 перейдет в A2, A2 — в A3 ,..., AN — в A1).

import random

N = int(input('Введи размер массива: '))
A = []
k = 0

while k < N:
    A.append(random.randrange(-10, 10))
    k += 1

print(A)

A = [A[-1]] + A[:-1]

print(A)
